### **Сводная схема (ER-модель)**

На основе предложенных таблиц, можно создать ER-модель (модель сущностей и их связей). В модели будут следующие основные сущности:

- **users** ↔ **reviews** (Пользователь оставляет отзывы)
- **users** ↔ **deals** (Пользователь может быть покупателем или продавцом)
- **listings** ↔ **reviews** (Каждое предложение может иметь несколько отзывов)
- **deals** ↔ **transactions** (Каждая сделка связана с транзакцией)
- **users** ↔ **chats** (Пользователи могут быть участниками чатов)
- **chats** ↔ **messages** (Чат содержит множество сообщений)
- **listings** ↔ **social_networks** (Предложение может быть связано с соцсетью)
- **listings** ↔ **categories** (Предложение может относиться к одной категории)

