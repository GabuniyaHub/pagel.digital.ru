### **1. Пользователи (Users)**
Сущность **users** уже существует в вашей базе данных. Это основная сущность, которая хранит информацию о каждом пользователе платформы.

**Поле `users`**:
- id (PRIMARY KEY)
- nickname (Уникальное имя пользователя)
- rating (Рейтинг пользователя на платформе)
- avatar (URL аватара пользователя)
- email (Уникальный email)
- password_hash (Хэш пароля)
- registration_date (Дата регистрации)
- description (Дополнительная информация о пользователе)
- google_id (ID Google для аутентификации)
- verified (Статус верификации пользователя)

---

### **2. Листинги (Listings)**
Сущность **listings** уже создана, и она будет хранить информацию о товарах или услугах, которые пользователи размещают на маркетплейсе.

**Поле `listings`**:
- id (PRIMARY KEY)
- link (Уникальная ссылка на предложение)
- theme (Тематика предложения)
- price (Цена предложения)
- income (Доход от услуги/товара)
- expense (Расходы, связанные с товаром или услугой)
- description (Описание товара/услуги)
- income_sources (Источники дохода)
- expense_sources (Источники расхода)
- promotion (Описание промо-акций)
- support_needs (Необходимая поддержка)
- allow_comments (Разрешить комментарии)
- show_link (Показывать ли ссылку на внешнюю платформу)
- flex_switch (Гибкость предложения)
- screenshots (Массив изображений, скриншотов предложения)
- created_at (Дата и время создания)

---

### **3. Отзывы (Reviews)**
Сущность **reviews** будет хранить информацию о отзывах, которые пользователи оставляют друг другу, чтобы повысить доверие на платформе.

**Поле `reviews`**:
- id (PRIMARY KEY)
- user_id (FOREIGN KEY на таблицу `users`, кто оставил отзыв)
- listing_id (FOREIGN KEY на таблицу `listings`, на какой товар/услугу оставлен отзыв)
- rating (Оценка товара/услуги)
- comment (Текст отзыва)
- created_at (Дата и время создания отзыва)

